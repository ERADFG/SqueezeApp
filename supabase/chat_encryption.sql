-- ── 6. SELF-TEST ──
-- Confirms the whole pipeline (secret readable, encrypt, decrypt) is
-- healthy right now, independent of any table data.
do $$
declare
  test_plain text := 'chat_pipeline_selftest_' || gen_random_uuid();
  test_result text;
begin
  test_result := public._chat_decrypt(encode(pgp_sym_encrypt(test_plain, public._chat_secret()), 'base64'), true);
  if test_result = test_plain then
    raise notice '✅ Chat encryption is set up and working.';
  else
    raise notice '❌ Self-test failed — decrypted value did not match. Check the chat_body_key Vault secret.';
  end if;
end $$;

